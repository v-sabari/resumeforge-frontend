/**
 * scripts/fetch-bundled-fonts.mjs
 *
 * One-time (re-runnable) build step that vendors the metric-compatible OFL
 * families the resume typography control offers, as base64 WOFF2 modules under
 * src/fonts/. The SAME bytes are then:
 *   - lazy-loaded by the live preview (src/fonts/index.js), and
 *   - embedded in the exported PDF (src/fonts/pdfFonts.js -> renderPdfHandler).
 * so the two surfaces resolve identical glyph metrics and can never disagree
 * on line wraps or page count.
 *
 * Source: Google Fonts (fonts.googleapis.com css2 API, latin subset, WOFF2).
 * Every family is licensed under the SIL Open Font License 1.1 — the license
 * text for each is committed alongside in src/fonts/licenses/.
 *
 * Usage: node scripts/fetch-bundled-fonts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const outDir = path.join(root, 'src', 'fonts');

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

// module id -> { css: Google Fonts family name, weights: [...] }
const FAMILIES = [
  { id: 'arimo',      css: 'Arimo',       weights: [400, 700] },
  { id: 'tinos',      css: 'Tinos',       weights: [400, 700] },
  { id: 'gelasio',    css: 'Gelasio',     weights: [400, 700] },
  { id: 'ebgaramond', css: 'EB Garamond', weights: [400, 700] },
  { id: 'carlito',    css: 'Carlito',     weights: [400, 700] },
  { id: 'caladea',    css: 'Caladea',     weights: [400, 700] },
  { id: 'cousine',    css: 'Cousine',     weights: [400, 700] },
];

async function fetchCss(cssFamily, weights) {
  const fam = cssFamily.replace(/ /g, '+');
  const url = `https://fonts.googleapis.com/css2?family=${fam}:wght@${weights.join(';')}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`css2 ${cssFamily}: HTTP ${res.status}`);
  return res.text();
}

/** Pull the /* latin *\/ @font-face blocks: [{weight, url}]. */
function latinFaces(css) {
  const out = [];
  // The subset comment PRECEDES its @font-face block, so match the pair.
  const re = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/gi;
  let m;
  while ((m = re.exec(css)) !== null) {
    const label = m[1];
    if (label !== 'latin') continue;
    const body = m[2];
    const weight = /font-weight:\s*(\d+)/.exec(body);
    const url = /src:\s*url\((https:[^)]+\.woff2)\)/.exec(body);
    if (weight && url) out.push({ weight: Number(weight[1]), url: url[1] });
  }
  return out;
}

async function main() {
  fs.mkdirSync(outDir, { recursive: true });
  const report = [];
  for (const fam of FAMILIES) {
    const css = await fetchCss(fam.css, fam.weights);
    const faces = latinFaces(css).filter((f) => fam.weights.includes(f.weight));
    if (faces.length !== fam.weights.length) {
      throw new Error(`${fam.css}: expected ${fam.weights.length} latin faces, got ${faces.length}`);
    }
    const entries = [];
    for (const face of faces) {
      const res = await fetch(face.url, { headers: { 'User-Agent': UA } });
      if (!res.ok) throw new Error(`${fam.css} ${face.weight}: HTTP ${res.status}`);
      const buf = Buffer.from(await res.arrayBuffer());
      entries.push({ weight: face.weight, base64: buf.toString('base64'), bytes: buf.length });
    }
    entries.sort((a, b) => a.weight - b.weight);
    const js =
      `/* AUTO-GENERATED by scripts/fetch-bundled-fonts.mjs — do not edit by hand.\n` +
      ` * ${fam.css} (latin subset, WOFF2), SIL Open Font License 1.1.\n` +
      ` * License text: src/fonts/licenses/${fam.id}-OFL.txt */\n` +
      `export const FAMILY = ${JSON.stringify(fam.css)};\n` +
      `export const FACES = [\n` +
      entries.map((e) => `  { weight: ${e.weight}, base64: '${e.base64}' },`).join('\n') +
      `\n];\n`;
    fs.writeFileSync(path.join(outDir, `${fam.id}.js`), js, 'utf8');
    const total = entries.reduce((s, e) => s + e.bytes, 0);
    report.push({ family: fam.css, id: fam.id, weights: entries.map((e) => `${e.weight}:${(e.bytes / 1024).toFixed(1)}KB`), totalKB: (total / 1024).toFixed(1) });
    console.log(`${fam.css.padEnd(14)} ${entries.map((e) => `${e.weight}=${(e.bytes / 1024).toFixed(1)}KB`).join('  ')}  total=${(total / 1024).toFixed(1)}KB`);
  }
  fs.writeFileSync(path.join(outDir, 'sizes.json'), JSON.stringify(report, null, 2), 'utf8');
  console.log(`\nwrote ${FAMILIES.length} modules to ${path.relative(root, outDir).replace(/\\/g, '/')}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
